'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const asar = require('@electron/asar');
const { profile } = require('../electron/ai-edition.cjs');
const resources = path.resolve(process.argv[2] || 'release/win-unpacked/resources');
const archive = path.join(resources, 'app.asar');
const metadata = JSON.parse(asar.extractFile(archive, 'package.json').toString());
assert.equal(metadata.kobeEdition, profile.id);
assert.equal(JSON.parse(asar.extractFile(archive, path.join('electron', 'editions', 'qwen3-only.json')).toString()).model, profile.model);
const modelRoot = path.join(resources, 'models');
assert.deepEqual(fs.readdirSync(modelRoot), ['models.json']);
const manifest = JSON.parse(fs.readFileSync(path.join(modelRoot, 'models.json')));
assert.equal(manifest.default, profile.model);
assert.deepEqual(manifest.models, []);
const libs = path.join(resources, 'ollama/win-x64/lib/ollama');
assert.ok(fs.existsSync(path.join(libs, 'ggml-cpu-x64.dll')));
for (const dir of ['cuda_v11', 'cuda_v12', 'cuda_v13']) assert.ok(!fs.existsSync(path.join(libs, dir)));
const backend = fs.readFileSync(path.join(resources, 'server-bundle/index.js'), 'utf8');
assert.ok(backend.includes('qwen3-only'));
assert.ok(fs.existsSync(path.join(resources, 'postgres/bin/initdb.exe')));
console.log('Qwen-only package verified: isolated edition, one-model setup, CPU runtime, backend and database.');
