import { BadRequestException, Injectable } from '@nestjs/common';
import { AiService } from '../ai/ai.service';
import { LiveSaleService } from './live-sale.service';

@Injectable()
export class LivePresenterService {
  constructor(private readonly sales: LiveSaleService, private readonly ai: AiService) {}

  async script(ownerId: string, sessionId: string) {
    const session = await this.sales.getSession(ownerId, sessionId);
    if (session.status !== 'LIVE' || session.kind === 'post') throw new BadRequestException('Open a live session first.');
    // Product facts are assembled from the live catalogue, never generated by the model.
    let introduction = 'Welcome to our live shop. I am your virtual presenter.';
    let aiGenerated = false;
    try {
      const draft = (await this.ai.chatCompletion({ messages: [
        { role: 'system', content: 'Output plain speech only, at most 30 words.' },
        { role: 'user', content: 'Write one short welcoming sentence for a live shopping host. Do not mention any products, prices, discounts, delivery, payments, or guarantees.' },
      ], signal: AbortSignal.timeout(15000), maxTokens: 80, mode: 'fast' })).content.trim();
      if (draft && draft.length <= 300) { introduction = draft; aiGenerated = true; }
    } catch { /* The catalogue presenter also works without an installed AI model. */ }
    // Inference can take several seconds: recheck the session and read current facts afterwards.
    const current = await this.sales.getSession(ownerId, sessionId);
    if (current.status !== 'LIVE') throw new BadRequestException('This sales session has ended.');
    const pins = await this.sales.listPins(ownerId, sessionId);
    const available = pins.filter(pin => Number(pin.stock) > 0);
    if (!available.length) throw new BadRequestException('Pin an in-stock product before starting the presenter.');
    const lines = available.map(pin => `${pin.name}. Price ${Number(pin.livePrice) > 0 ? Number(pin.livePrice) : Number(pin.catalogPrice)} ${session.currency}. ${Number(pin.stock)} available. Comment ${pin.code} to reserve, or open our live shop to buy.`);
    return { script: [introduction, ...lines].join('\n\n'), aiGenerated, products: available, currency: session.currency };
  }
}
